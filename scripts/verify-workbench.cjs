const { app, BrowserWindow } = require('electron')
const fs = require('node:fs/promises')
const path = require('node:path')
const root = path.resolve(__dirname, '..')
app.disableHardwareAcceleration()
setTimeout(() => { console.error('Workbench verification timed out'); app.exit(1) }, 90_000).unref()
const delay = (ms = 200) => new Promise(resolve => setTimeout(resolve, ms))
async function main() {
  app.setPath('userData', path.join(root, '.workbench-preview-profile'))
  await app.whenReady()
  const { createServer } = await import('vite')
  const react = (await import('@vitejs/plugin-react')).default
  const vite = await createServer({ configFile: false, root: path.join(root, 'src/renderer'), plugins: [react()],
    resolve: { alias: { '@shared': path.join(root, 'src/shared') } }, server: { host: '127.0.0.1', port: 4320, strictPort: true } })
  await vite.listen()
  const win = new BrowserWindow({ width: 1450, height: 950, show: false, offscreen: true,
    webPreferences: { contextIsolation: true, sandbox: true, backgroundThrottling: false } })
  const errors = []
  win.webContents.on('console-message', (event) => { if (event.level === 'error') { errors.push(event.message); console.error('Renderer:', event.message) } })
  const run = code => win.webContents.executeJavaScript(code)
  const waitFor = async code => {
    for (let i = 0; i < 100; i++) { if (await run(code)) return; await delay(100) }
    throw new Error(`Timed out: ${code}`)
  }
  const check = async (code, label) => { if (!await run(code)) throw new Error(label); console.log(`Passed: ${label}`) }
  const click = async (selector, text) => { await run(`(() => { const el = [...document.querySelectorAll(${JSON.stringify(selector)})].find(el => ${text ? `el.textContent.includes(${JSON.stringify(text)})` : 'true'}); if (!el) throw new Error('Missing button'); el.click() })()`); await delay() }
  const capture = async name => {
    // Resizing forces a fresh offscreen surface on Windows; invalidate alone can
    // retain a previous page after hiding an xterm canvas.
    const [width, height] = win.getSize()
    win.setSize(width + 1, height)
    await delay(150)
    win.setSize(width, height)
    await delay(300)
    await fs.writeFile(path.join(root, 'artifacts', name), (await win.webContents.capturePage()).toPNG())
  }
  await fs.mkdir(path.join(root, 'artifacts'), { recursive: true })
  await win.loadURL('http://127.0.0.1:4320/screenshot-harness.html')
  await waitFor('window.__captureReady && document.querySelectorAll(".wb-gpu-table tbody tr").length === 4')
  await run('document.fonts.ready')
  await capture('workbench-resource.png')
  await check('document.querySelectorAll(".wb-host-summary > div").length === 4 && document.querySelectorAll(".wb-storage-summary > div > button").length === 2', 'server summary includes resources and mounted storage')
  await click('[aria-label="查看 GPU 2 详情"]')
  await waitFor('document.querySelector(".wb-device-page") && document.querySelectorAll(".history-series").length === 4')
  await check('document.querySelector(".wb-device-header h1").textContent === "gpu8 / GPU 2" && !document.querySelector(".gpu-overlay")', 'server GPU opens exact device in workbench, without legacy modal')
  await capture('workbench-gpu-detail.png')
  await click('.gpu-selector button', 'GPU 1')
  await check('document.querySelector(".wb-device-header h1").textContent === "gpu8 / GPU 1"', 'device switch updates GPU heading')
  await click('[aria-label="返回 GPU 来源页面"]')
  await check('document.querySelector(".resource-workbench") && document.querySelector(".wb-gpu-inspector h3").textContent === "GPU 1"', 'back returns to server context and selected GPU')
  await click('.workbench-browser-links button', 'GPU 总览')
  await waitFor('document.querySelectorAll(".wb-pool-table tbody tr").length === 6')
  await check('!document.querySelector(".gpu-overview-card") && document.querySelectorAll(".wb-recommendations button").length === 2', 'resource pool uses shared table and live recommendations')
  await capture('workbench-gpu-pool.png')
  await run(`(() => { const el = document.querySelector('[aria-label="GPU 总览服务器筛选"]'); el.value = 'demo-gpu-01'; el.dispatchEvent(new Event('change', { bubbles: true })); })()`)
  await waitFor('document.querySelectorAll(".wb-pool-table tbody tr").length === 4')
  await click('[aria-label="查看 gpu8 GPU 0 详情"]')
  await waitFor('document.querySelector(".wb-device-header h1")?.textContent === "gpu8 / GPU 0"')
  await click('[aria-label="返回 GPU 来源页面"]')
  await check(`document.querySelector('.wb-pool-table') && document.querySelector('[aria-label="GPU 总览服务器筛选"]').value === 'demo-gpu-01' && document.querySelectorAll('.wb-pool-table tbody tr').length === 4`, 'back preserves GPU pool source and filters')
  await click('.sidebar-server-link', 'gpu8')
  await click('.workbench-browser-links button', '全部服务器')
  await waitFor('document.querySelectorAll(".wb-all-server-table tbody tr").length === 3')
  await capture('workbench-all-servers.png')
  await click('[aria-label="查看 gpu8 GPU 3 详情"]')
  await check('document.querySelector(".wb-device-header h1")?.textContent === "gpu8 / GPU 3"', 'all-server list opens each individual GPU')
  await click('[aria-label="返回 GPU 来源页面"]')
  await check('document.querySelector(".wb-all-server-table")', 'GPU detail returns to all-server list')
  await click('.sidebar-server-link', 'gpu8')
  await click('.wb-host-actions button', '连接终端')
  await waitFor('window.__labPreview.terminalConnects === 1')
  await capture('workbench-terminal.png')
  await click('.workbench-dock-heading > button')
  await click('.workbench-modulebar .nav-button', '实验任务')
  await waitFor('document.querySelectorAll(".experiment-pool-table tbody tr").length === 4')
  await check('window.__labPreview.terminalConnects === 1 && window.__labPreview.terminalCloses === 0', 'terminal survives collapse and page change')
  await capture('workbench-task-list.png')
  await check(`document.querySelector('[aria-label="删除任务 LISA 复现"]').disabled && !document.querySelector('[aria-label="删除任务 LISA 复现 · 已取消"]').disabled`, 'running protected, cancelled task deletable')
  await click('.experiment-pool-table .wb-text-button', 'LISA 复现 · 已取消')
  await capture('workbench-tasks.png')
  await click('[aria-label="删除任务 LISA 复现 · 已取消"]')
  await check('document.querySelector("[role=alertdialog]")?.textContent.includes("1 次运行记录")', 'delete confirmation explains history removal')
  await click('.confirm-dialog .secondary-button')
  await check('document.querySelectorAll(".experiment-pool-table tbody tr").length === 4', 'cancel deletion retains task')
  await click('[aria-label="删除任务 LISA 复现 · 已取消"]')
  await click('.confirm-dialog .dialog-footer .danger-button')
  await waitFor('document.querySelectorAll(".experiment-pool-table tbody tr").length === 3')
  await click('.sidebar-server-link', 'gpu7')
  await check('document.querySelector(".wb-server-identity h1").textContent === "gpu7"', 'sidebar switches resource context')
  await check('window.__labPreview.terminalConnects === 1 && window.__labPreview.terminalCloses === 0', 'server selection preserves original SSH session')
  await click('.wb-host-actions button', '打开文件')
  await waitFor('document.querySelectorAll(".file-row").length === 2')
  await check('window.__labPreview.sftpReads.at(-1).serverId === "demo-gpu-02"', 'embedded files use selected server')
  await capture('workbench-files.png')
  await click('.workbench-modulebar .nav-button', '资源')
  await click('.wb-gpu-inspector > button')
  await waitFor('document.querySelector(".experiment-auto-gpu-note")')
  await check('document.querySelector(".experiment-auto-gpu-note").textContent.includes("GPU 1")', 'new task retains selected GPU')
  await run(`(() => { const el = document.querySelector('.app-modal input'); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(el, 'GPU 定向验证'); el.dispatchEvent(new Event('input', { bubbles: true })); })()`)
  await run(`(() => { const el = document.querySelector('.app-modal input[placeholder="/home/user/project"]'); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(el, '/home/researcher/code'); el.dispatchEvent(new Event('input', { bubbles: true })); })()`)
  await run(`(() => { const el = [...document.querySelectorAll('.app-modal textarea')].find(el => el.placeholder.includes('python')); if (!el) throw new Error('command input missing'); Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype, 'value').set.call(el, 'python train.py'); el.dispatchEvent(new Event('input', { bubbles: true })); })()`)
  await click('.app-modal .primary-button', '保存并排队')
  await waitFor('window.__labPreview.startedRuns.length === 1')
  await check('window.__labPreview.startedRuns[0].serverId === "demo-gpu-02" && window.__labPreview.startedRuns[0].gpuIndex === 1', 'queued task uses selected server and GPU')
  await click('.workbench-modulebar .nav-button', '终端')
  await check('window.__labPreview.terminalConnects === 1 && window.__labPreview.terminalCloses === 0 && document.querySelector(".workbench-terminal-dock.fullscreen")', 'fullscreen terminal reuses session')
  await click('.workbench-modulebar .nav-button', '资源')
  await click('.workbench-modulebar .nav-button', '实验任务')
  await check('!document.querySelector(".experiment-editor") && !document.querySelector(".app-modal")', 'completed new-task request does not reopen editor on navigation')
  await click('.workbench-modulebar .nav-button', '资源')
  await run('document.documentElement.dataset.theme = "instrument"')
  await capture('workbench-light.png')
  await click('.wb-gpu-select')
  await waitFor('document.querySelectorAll(".history-series").length === 4')
  await capture('workbench-gpu-detail-light.png')
  await check('window.__labPreview.terminalConnects === 1 && window.__labPreview.terminalCloses === 0', 'GPU page navigation preserves existing terminal')
  await click('[aria-label="返回 GPU 来源页面"]')
  await win.setSize(850, 950)
  await delay()
  await check('document.querySelector(".workbench-main").scrollWidth <= document.querySelector(".workbench-main").clientWidth', 'narrow window contains table overflow')
  await capture('workbench-narrow.png')
  await run('window.__labPreview.offlineServers.push("demo-gpu-01")')
  await click('.workbench-browser-links button', 'GPU 总览')
  await click('.wb-resource-pool .workbench-page-heading button')
  await waitFor('[...document.querySelectorAll(".wb-pool-table tbody tr")].every(el => el.textContent.includes("待确认"))')
  await check('document.querySelectorAll(".wb-recommendations button").length === 1 && document.querySelector(".wb-recommendations button").textContent.includes("gpu7")', 'offline GPUs excluded from availability suggestions')
  await click('[aria-label="查看 gpu8 GPU 3 详情"]')
  await check('document.querySelector(".wb-device-header .primary-button").disabled && document.querySelector(".wb-device-page .wb-notice").textContent.includes("离线")', 'offline device details do not imply schedulable state')
  await run('window.__labPreview.offlineServers.length = 0; window.__labPreview.cachedServers.push("demo-gpu-01")')
  await click('.wb-device-header .secondary-button', '刷新设备')
  await waitFor('document.querySelector(".wb-device-page .gpu-state").textContent.includes("待确认")')
  await check('document.querySelector(".wb-device-header .primary-button").disabled', 'cached device cannot create a directed run until refreshed live')
  if (errors.length) throw new Error(errors.join('\n'))
  win.close()
  await vite.close()
  app.quit()
}
main().catch(error => { console.error(error); app.exit(1) })
